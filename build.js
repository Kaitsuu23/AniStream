#!/usr/bin/env node
// build.js — Bakes BACKEND_URL and CF_WORKER_URL into public/js/config.js
// Run: node build.js
// No external dependencies required.

const fs = require('fs');
const path = require('path');

// ── Minimal .env parser (no dotenv dependency) ───────────────────────────────
function loadDotEnv(envPath) {
  const result = {};
  if (!fs.existsSync(envPath)) return result;
  const lines = fs.readFileSync(envPath, 'utf8').split('\n');
  for (const raw of lines) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let val = line.slice(eq + 1).trim();
    // Strip surrounding quotes (single or double)
    if ((val.startsWith('"') && val.endsWith('"')) ||
        (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    result[key] = val;
  }
  return result;
}

// Load .env file values as defaults (process.env takes priority)
const dotEnvVars = loadDotEnv(path.join(__dirname, '.env'));
for (const [key, val] of Object.entries(dotEnvVars)) {
  if (!(key in process.env)) {
    process.env[key] = val;
  }
}

// Read the two variables; default to empty string if absent or empty
const BACKEND_URL = (process.env.BACKEND_URL || '').trim();
const CF_WORKER_URL = (process.env.CF_WORKER_URL || '').trim();

// ── Config template (always rebuilt from here, never reads config.js) ────────
const configContent = `// Auto-generated by build.js — do not edit manually.
window.API_BASE_URL = '${BACKEND_URL}';
window.CF_WORKER_URL = '${CF_WORKER_URL}';
`;

// Write to public/js/config.js
const outPath = path.join(__dirname, 'public', 'js', 'config.js');
fs.writeFileSync(outPath, configContent, 'utf8');

// Log result (mask CF worker URL after first 20 chars for safety)
const maskedCf = CF_WORKER_URL.length > 20
  ? CF_WORKER_URL.slice(0, 20) + '...'
  : CF_WORKER_URL || '(empty)';

console.log('build.js: wrote public/js/config.js');
console.log('  BACKEND_URL   =', BACKEND_URL || '(empty — using relative URLs)');
console.log('  CF_WORKER_URL =', maskedCf);
